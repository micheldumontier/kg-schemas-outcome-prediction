"""Summary of the semantic-enrichment arms (plan A): AUC per arm and paired comparisons with the random arm.

Usage: python aggregate_arms.py <results dir> [seeds, default 0,1,2] [--tex out.tex]
Each arm's AUC is averaged over seeds within each fold (the folds share test patients across arms and seeds), then
compared with the random arm by a paired t-test over the 10 folds. Also reports the spread between seeds.
"""
import json, sys
from pathlib import Path
import numpy as np
from scipy import stats

ARMS = ['random', 'shuffled', 'sapbert', 'owl2vec', 'hier', 'hier_omop']


def fold_aucs(results_dir, arm, seed):
    files = sorted(Path(results_dir, f'MIMIC24s{seed}_arm_{arm}').glob('fold*.json'), key=lambda p: int(p.stem[4:]))
    if len(files) != 10:
        raise ValueError(f'MIMIC24s{seed}_arm_{arm} has {len(files)} folds, expected 10')
    return np.array([json.loads(f.read_text())['auc_weighted'] for f in files])


def summarise(results_dir, seeds=(0, 1, 2), arms=ARMS):
    """Rows of (arm, mean AUC, sd over folds, seed range, difference with random, p) for complete arms."""
    per_arm = {}
    for arm in arms:
        try:
            per_arm[arm] = np.array([fold_aucs(results_dir, arm, s) for s in seeds])     # [seed, fold]
        except ValueError:
            continue
    base = per_arm.get('random')
    rows = []
    for arm, a in per_arm.items():
        f = a.mean(0)
        seed_means = a.mean(1)
        diff = p = None
        if base is not None and arm != 'random':
            diff, p = (f - base.mean(0)).mean(), stats.ttest_rel(f, base.mean(0)).pvalue
        rows.append((arm, f.mean(), f.std(ddof=1), seed_means.max() - seed_means.min(), diff, p))
    return rows


KEYS = {'random': 'Random', 'shuffled': 'Shuffled', 'sapbert': 'Sapbert', 'owl2vec': 'Owl', 'hier': 'Hier',
        'hier_omop': 'Hieromop'}


def arm_macros(results_dir, seeds=(0, 1, 2)):
    """LaTeX macros: AUC per arm, difference and p against random, and the largest difference and smallest p."""
    rows = summarise(results_dir, seeds)
    if len(rows) != len(ARMS):
        raise ValueError(f'only {len(rows)} of {len(ARMS)} arms complete')
    signed = lambda v: f'{v:+.3f}'.replace('-', '$-$')
    lines = ['% generated by followup/kg/aggregate_arms.py; do not edit']
    for arm, m, sd, _, d, p in rows:
        lines.append(f'\\newcommand{{\\maucArm{KEYS[arm]}}}{{{m:.3f}\\,$\\pm$\\,{sd:.3f}}}')
        if d is not None:
            lines.append(f'\\newcommand{{\\mdiffArm{KEYS[arm]}}}{{{signed(d)}}}')
            lines.append(f'\\newcommand{{\\mpArm{KEYS[arm]}}}{{{p:.2f}}}')
    diffs = [(abs(d), p) for *_, d, p in rows if d is not None]
    lines.append(f'\\newcommand{{\\mArmMaxDiff}}{{{max(a for a, _ in diffs):.3f}}}')
    lines.append(f'\\newcommand{{\\mArmMinP}}{{{min(p for _, p in diffs):.2f}}}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    if '--tex' in sys.argv:
        out = sys.argv[sys.argv.index('--tex') + 1]
        Path(out).write_text(arm_macros(sys.argv[1]))
        print('wrote', out)
        sys.exit()
    seeds = tuple(int(s) for s in sys.argv[2].split(',')) if len(sys.argv) > 2 else (0, 1, 2)
    print(f'{"arm":10s} {"AUC":>7s} {"sd":>6s} {"seed range":>10s} {"vs random":>9s} {"p":>6s}')
    for arm, m, sd, rng, d, p in summarise(sys.argv[1], seeds):
        print(f'{arm:10s} {m:7.3f} {sd:6.3f} {rng:10.3f} ' + (f'{d:+9.3f} {p:6.3f}' if d is not None else ''))
