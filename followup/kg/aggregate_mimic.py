"""LaTeX macros for the MIMIC-IV results: 10-fold means and paired fold comparisons. Refuses incomplete runs.

Usage: python aggregate_mimic.py <results dir with MIMIC24_* folders> <output .tex> [--robustness]
With --robustness, also writes tagged macros (e.g. \\maucSPHNHfortyeight) for the 48 h and 72 h landmarks and for
seeds 1 and 2 at 24 h.
"""
import json, sys
from pathlib import Path
import numpy as np
from scipy import stats

RUNS = {'GBM': 'GBM', 'LR': 'LR', 'caresm_ts': 'CARE', 'caresm_comp': 'COMP', 'sphn_ts': 'SPHN', 'sphn_tsr': 'SPHNtr',
        'EVENTS_GBM': 'Events', 'AGE_GBM': 'Age',
        'sphn_ts_bidir': 'SPHNbidir', 'sphn_real': 'SPHNreal', 'sphn_real_text': 'SPHNtext'}
PAIRS = [('caresm_ts', 'sphn_ts', 'CAREvsSPHN'), ('caresm_comp', 'caresm_ts', 'COMPvsCARE'), ('sphn_tsr', 'sphn_ts', 'TRvsTS'),
         ('GBM', 'caresm_ts', 'GBMvsCARE'), ('GBM', 'sphn_ts', 'GBMvsSPHN'),
         ('sphn_ts_bidir', 'sphn_ts', 'BIDIRvsTS'), ('sphn_real', 'sphn_ts_bidir', 'REALvsBIDIR'),
         ('sphn_real_text', 'sphn_real', 'TEXTvsREAL'), ('GBM', 'sphn_real', 'GBMvsREAL')]


GRAPH = {k: v for k, v in RUNS.items() if k in ('caresm_ts', 'caresm_comp', 'sphn_ts', 'sphn_tsr')}
# prefix, macro tag, runs, pairs
LANDMARK_RUNS = {**GRAPH, 'GBM': 'GBM', 'LR': 'LR', 'EVENTS_GBM': 'Events', 'AGE_GBM': 'Age'}
ROBUSTNESS = [('MIMIC48', 'Hfortyeight', LANDMARK_RUNS, PAIRS[:5]),
              ('MIMIC72', 'Hseventytwo', LANDMARK_RUNS, PAIRS[:5]),
              ('MIMIC24s1', 'Sone', GRAPH, PAIRS[:3]),
              ('MIMIC24s2', 'Stwo', GRAPH, PAIRS[:3])]


def folds(results_dir, run, metric='auc_weighted', prefix='MIMIC24'):
    files = sorted(Path(results_dir, f'{prefix}_{run}').glob('fold*.json'))
    if len(files) != 10:
        raise ValueError(f'{prefix}_{run} has {len(files)} folds, expected 10')
    return np.array([json.loads(f.read_text())[metric] for f in sorted(files, key=lambda p: int(p.stem[4:]))])


def signed(v):
    """Signed difference with a typographic minus, e.g. $-$0.003 or +0.017."""
    return f'{v:+.3f}'.replace('-', '$-$')


def mimic_macros(results_dir, runs=RUNS, pairs=PAIRS, prefix='MIMIC24', tag=''):
    lines = [f'% generated by followup/kg/aggregate_mimic.py ({prefix}); do not edit']
    for run, key in runs.items():
        for metric, short in [('auc_weighted', 'mauc'), ('acc', 'macc')]:
            v = folds(results_dir, run, metric, prefix)
            lines.append(f'\\newcommand{{\\{short}{key}{tag}}}{{{v.mean():.3f}\\,$\\pm$\\,{v.std(ddof=1):.3f}}}')
    for a, b, key in pairs:
        x, y = folds(results_dir, a, prefix=prefix), folds(results_dir, b, prefix=prefix)
        lines.append(f'\\newcommand{{\\mdiff{key}{tag}}}{{{signed((x - y).mean())}}}')
        lines.append(f'\\newcommand{{\\mp{key}{tag}}}{{{stats.ttest_rel(x, y).pvalue:.2f}}}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    tex = mimic_macros(sys.argv[1])
    if '--robustness' in sys.argv:
        tex += ''.join(mimic_macros(sys.argv[1], runs, pairs, prefix, tag) for prefix, tag, runs, pairs in ROBUSTNESS)
    Path(sys.argv[2]).write_text(tex)
    print('wrote', sys.argv[2])
