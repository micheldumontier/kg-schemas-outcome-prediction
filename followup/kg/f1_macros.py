"""LaTeX macros for macro-F1 (10-fold mean and SD) of the runs in Table 2 of the MIE paper.

Usage: python f1_macros.py <repro results dir> <mimic24 results dir> <output .tex>
e.g. from the repository root: python followup/kg/f1_macros.py repro/results followup/results/mimic24 f1macro.tex
Synthetic runs (repro/results) give \\fmac<key>, MIMIC-IV runs at 24 h give \\mfmac<key>, with the keys of the existing
AUC and accuracy macros (numbers.tex and mimic.tex). Aggregates only.
"""
import json, sys
from pathlib import Path
import numpy as np

SYNTHETIC = {'S': 'S', 'G': 'G', 'A': 'A', 'E': 'E', 'E5': 'Efive', 'F': 'F', 'ROUNDTRIP_RF': 'Roundtrip', 'LR': 'LR',
             'AGE_RF': 'AgeRF'}
MIMIC = {'GBM': 'GBM', 'caresm_ts': 'CARE', 'caresm_comp': 'COMP', 'LR': 'LR', 'sphn_ts': 'SPHN', 'sphn_tsr': 'SPHNtr',
         'sphn_real': 'SPHNreal', 'EVENTS_GBM': 'Events', 'AGE_GBM': 'Age'}


def f1(run_dir):
    files = sorted(Path(run_dir).glob('fold*.json'), key=lambda p: int(p.stem[4:]))
    if len(files) != 10:
        raise ValueError(f'{run_dir} has {len(files)} folds, expected 10')
    v = np.array([json.loads(f.read_text())['f1_macro'] for f in files])
    return f'{v.mean():.3f}\\,$\\pm$\\,{v.std(ddof=1):.3f}'


def macros(repro_dir, mimic_dir):
    lines = ['% generated by followup/kg/f1_macros.py; do not edit']
    lines += [f'\\newcommand{{\\fmac{k}}}{{{f1(Path(repro_dir, run))}}}' for run, k in SYNTHETIC.items()]
    lines += [f'\\newcommand{{\\mfmac{k}}}{{{f1(Path(mimic_dir, "MIMIC24_" + run))}}}' for run, k in MIMIC.items()]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    Path(sys.argv[3]).write_text(macros(sys.argv[1], sys.argv[2]))
    print('wrote', sys.argv[3])
