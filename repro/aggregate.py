"""Turn per-fold JSON into LaTeX macros and the consolidated results table. Refuses incomplete runs."""
import json, sys
from pathlib import Path
import numpy as np

KEY = {'A': 'A', 'B': 'B', 'E': 'E', 'F': 'F', 'S': 'S', 'G': 'G', 'D2': 'Dtwo',
       'LR': 'LR', 'RF': 'RF', 'NN': 'NN', 'AGE': 'Age', 'AGE_RF': 'AgeRF', 'EVENTS_RF': 'EventsRF',
       'LR_SEPT2024': 'LRsept', 'RF_SEPT2024': 'RFsept', 'NN_SEPT2024': 'NNsept', 'ROUNDTRIP_RF': 'Roundtrip', 'E5': 'Efive', 'F5': 'Ffive'}
METRICS = {'auc_weighted': 'auc', 'acc': 'acc', 'f1_backhome': 'foneBH', 'f1_rehab': 'foneRE', 'f1_death': 'foneDE'}


def summarise(results_dir, runs, n_folds=10):
    out = {}
    for run in runs:
        files = sorted(Path(results_dir, run).glob('fold*.json'))
        if len(files) != n_folds:
            raise ValueError(f'{run} has {len(files)} folds, expected {n_folds}')
        recs = [json.loads(f.read_text()) for f in files]
        out[run] = {m: (float(np.mean([r[m] for r in recs])), float(np.std([r[m] for r in recs], ddof=1)))
                    for m in METRICS}
    return out


def fmt(ms):
    return f'{ms[0]:.3f}\\,$\\pm$\\,{ms[1]:.3f}'


def macro_name(run, short):
    return 'fone' + KEY[run] + short[4:] if short.startswith('fone') else short + KEY[run]


def macros(summary):
    lines = ['% generated by repro/aggregate.py; do not edit']
    for run, ms in summary.items():
        for m, short in METRICS.items():
            lines.append(f'\\newcommand{{\\{macro_name(run, short)}}}{{{fmt(ms[m])}}}')
    return '\n'.join(lines) + '\n'


def partial_macros(results_dir, runs, n_folds=10):
    """Drafting aid: real values for runs with all folds, \\textbf{??} for runs still in progress."""
    complete = [r for r in runs if len(list(Path(results_dir, r).glob('fold*.json'))) == n_folds]
    tex = macros(summarise(results_dir, complete, n_folds)).splitlines()
    tex[0] = '% generated by repro/aggregate.py --partial; runs still in progress show ??'
    for run in runs:
        if run not in complete:
            tex += [f'\\newcommand{{\\{macro_name(run, short)}}}{{\\textbf{{??}}}}' for short in METRICS.values()]
    return '\n'.join(tex) + '\n'


# (label, run, layers, paper AUC); a row with run None is a group header
ROWS = [('As published', None, None, None),
        ('CARE-SM*-ts, RGCN+lit', 'A', 3, '0.50'),
        ('CARE-SM*-ts, RGCN+lit', 'B', 5, '0.50'),
        ('SPHN-ts, RGCN+lit', 'S', 3, '0.91'),
        ('Logistic regression, Sept-2024 CSV', 'LR_SEPT2024', None, '0.70'),
        ('Random forest, Sept-2024 CSV', 'RF_SEPT2024', None, '0.71'),
        ('Neural network, Sept-2024 CSV', 'NN_SEPT2024', None, '0.63'),
        ('Diagnostics on the graph pipeline\'s CSV', None, None, None),
        ('CARE-SM, literal filter fixed', 'E', 4, None),
        ('CARE-SM, fixed, unit-scale embeddings', 'F', 4, None),
        ('SPHN, \\texttt{hasAge} as \\texttt{hasDiagnosis}', 'G', 3, None),
        ('CARE-SM plus \\texttt{hasOutcome}', 'D2', 3, None),
        ('Logistic regression, all features', 'LR', None, None),
        ('Random forest, features read from CARE-SM', 'ROUNDTRIP_RF', None, None),
        ('Random forest, age only', 'AGE_RF', None, None),
        ('Random forest, care events only', 'EVENTS_RF', None, None)]


def table(summary):
    body = []
    for label, r, layers, paper in ROWS:
        if r is None:
            body.append(f'\\multicolumn{{5}}{{l}}{{\\textit{{{label}}}}} \\\\')
        else:
            auc, acc = ((fmt(summary[r]['auc_weighted']), fmt(summary[r]['acc'])) if r in summary
                        else ('\\textbf{??}', '\\textbf{??}'))
            body.append(f'{label} & {layers or "--"} & {auc} & {acc} & {paper or "--"} \\\\')
    return ('% generated by repro/aggregate.py; do not edit\n\\begin{tabular}{lcccc}\n\\hline\n'
            'Configuration & Layers & AUC & Accuracy & Paper AUC \\\\\n\\hline\n' + '\n'.join(body)
            + '\n\\hline\n\\end{tabular}\n')


if __name__ == '__main__':
    runs = list(KEY)
    if '--partial' in sys.argv:
        out = Path(sys.argv[2])
        out.mkdir(parents=True, exist_ok=True)
        (out / 'numbers.tex').write_text(partial_macros(Path(sys.argv[1]), runs))
        done = [r for r in runs if len(list(Path(sys.argv[1], r).glob('fold*.json'))) == 10]
        (out / 'results_table.tex').write_text(table(summarise(Path(sys.argv[1]), done)))
        print('wrote partial', out / 'numbers.tex', out / 'results_table.tex')
        sys.exit(0)
    s = summarise(Path(sys.argv[1]), runs)
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    (out / 'numbers.tex').write_text(macros(s))
    (out / 'results_table.tex').write_text(table(s))
    print('wrote', out / 'numbers.tex', out / 'results_table.tex')
